//Anonymous types in C#

//Anonymous types let you create objects with read-only properties without defining a class first.
//They're perfect for temporary data groupings within a method, such as combining a few related values before formatting or projecting them.

//When you print a decimal directly with string interpolation, C# shows only the digits it stored.
//So 10m prints as 10, while 10.50m prints as 10.50.
//For money, you usually want a consistent number of decimal places. Use a format specifier inside the interpolation to control this.

//Key characteristics of anonymous types:
//      - Properties are read-only (immutable).
//      - The type is generated by the compiler.
//      - Use var since you can't name the type.
//      - Great for LINQ projections and temporary data.


//Creating anonymous types
var person = new { Name = "Alice", Age = 30 };  //Basic syntax with new { }

string city = "London";                         //Property names inferred from variable names
int population = 9000000;
var cityInfo = new { city, population };

var item = new { Name = "Widget", price, InStock = true };      //Mixed: some explicit, some inferred


//Accessing properties
var book = new { Title = "C# Basics", Pages = 350, Price = 29.99m };

Console.WriteLine(book.Title);  //"C# Basics"
Console.WriteLine(book.Pages);  //350
Console.WriteLine(book.Price);  //29.99


//Formatting numbers consistently
decimal amount = 5m;
Console.WriteLine($"{amount}");     //5
Console.WriteLine($"{amount:F2}");  //5.00  (always 2 decimals)

decimal tax = 8.5m;
Console.WriteLine($"{tax:F2}");     //8.50



//Test: create an anonymous type to hold product information (name, price, quantity), then format it into a description string.
//      The price must always display with exactly two decimal places
//      (for example, a price of 10 becomes $10.00 and a price of 75.5 becomes $75.50).
//      The required format is:
//          Product: { Name}, Price: ${ Price}, Qty: { Quantity}
public class Solution
{
    public static string DescribeProduct(string name, decimal price, int quantity)
    {
        var product = new { name, price, quantity };
        return $"Product: {product.name}, Price: {product.price:C2}, Qty: {product.quantity}";
    }                                   //:C2 uses 2 decimal places and places a different currency symbol based on the machine's culture.
}